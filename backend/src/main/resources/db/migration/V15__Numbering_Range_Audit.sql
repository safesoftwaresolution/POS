-- V15__Numbering_Range_Audit.sql
-- Registro de auditoria de cambios sobre rangos de numeracion DIAN/Factus (creacion, eliminacion,
-- activacion/desactivacion y cambio de consecutivo). El rango de numeracion lo administra el propio
-- local (ADMINISTRATOR), pero afecta la numeracion legal ante la DIAN, asi que cada cambio queda
-- registrado con quien lo hizo.
CREATE TABLE numbering_range_audit (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY,
    store_id       BIGINT       NOT NULL,
    range_id       BIGINT       NOT NULL,
    action         VARCHAR(20)  NOT NULL,
    previous_value VARCHAR(50),
    new_value      VARCHAR(50),
    performed_by   VARCHAR(100),
    created_at     TIMESTAMP    NOT NULL,

    CONSTRAINT PK_numbering_range_audit PRIMARY KEY (id),
    CONSTRAINT FK_numbering_range_audit_store FOREIGN KEY (store_id) REFERENCES stores(id),
    CONSTRAINT CK_numbering_range_audit_action CHECK (action IN
        ('CREATE', 'DELETE', 'ACTIVATE', 'DEACTIVATE', 'UPDATE_CURRENT'))
);

CREATE INDEX IDX_numbering_range_audit_store_range ON numbering_range_audit(store_id, range_id);
