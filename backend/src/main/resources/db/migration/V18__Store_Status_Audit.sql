-- Historial de auditoria (solo lectura) de los cambios de estado de un local: registro, aprobacion,
-- rechazo, suspension, etc. Hasta ahora solo se veian los locales PENDING_VERIFICATION; de los
-- aprobados no quedaba rastro de quien/cuando. Cada fila es inmutable: la aplicacion solo inserta.
CREATE TABLE store_status_audit (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY,
    store_id        BIGINT       NOT NULL,
    previous_status VARCHAR(30),
    new_status      VARCHAR(30)  NOT NULL,
    reason          VARCHAR(255),
    performed_by    VARCHAR(100),
    created_at      TIMESTAMP    NOT NULL,

    CONSTRAINT PK_store_status_audit PRIMARY KEY (id),
    CONSTRAINT FK_store_status_audit_store FOREIGN KEY (store_id) REFERENCES stores(id)
);

CREATE INDEX IDX_store_status_audit_store ON store_status_audit(store_id, created_at);
CREATE INDEX IDX_store_status_audit_status ON store_status_audit(new_status, created_at);

-- Backfill: los locales que ya salieron de PENDING_VERIFICATION no tienen historial. Se deja una
-- fila con el estado actual y updated_at como mejor aproximacion; performed_by queda NULL porque
-- el actor original no se registro.
INSERT INTO store_status_audit (store_id, previous_status, new_status, reason, performed_by, created_at)
SELECT id, NULL, status, rejection_reason, NULL, updated_at
FROM stores
WHERE status <> 'PENDING_VERIFICATION';
