-- V19__Password_Reset_Tokens.sql
-- Tokens de recuperacion de contrasena: opacos (solo se guarda el hash SHA-256), de un solo uso y con
-- expiracion corta. Mismo esquema que email_verification_tokens (V7).
CREATE TABLE password_reset_tokens (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY,
    token_hash VARCHAR(64) NOT NULL,
    user_id    BIGINT      NOT NULL,
    expires_at TIMESTAMP   NOT NULL,
    used_at    TIMESTAMP,
    created_at TIMESTAMP   NOT NULL,

    CONSTRAINT PK_password_reset_tokens PRIMARY KEY (id),
    CONSTRAINT UK_prt_hash UNIQUE (token_hash),
    CONSTRAINT FK_prt_user FOREIGN KEY (user_id) REFERENCES users(id)
);

CREATE INDEX IDX_prt_user ON password_reset_tokens(user_id);
