-- V21__Store_User_Audit.sql
-- Historial inmutable de asignaciones de usuarios a locales hechas por el SUPER_ADMIN desde el backoffice
-- (un local sin dueño recibe a un ADMINISTRATOR que aun no tenia local). Solo se inserta. Sin FKs a stores
-- ni users: guarda una copia de los datos, igual que store_status_audit (V20), para sobrevivir a borrados.
CREATE TABLE store_user_audit (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY,
    store_id     BIGINT       NOT NULL,
    store_name   VARCHAR(100),
    user_id      BIGINT       NOT NULL,
    username     VARCHAR(50),
    full_name    VARCHAR(100),
    role         VARCHAR(20),
    action       VARCHAR(20)  NOT NULL,
    performed_by VARCHAR(100),
    created_at   TIMESTAMP    NOT NULL,

    CONSTRAINT PK_store_user_audit PRIMARY KEY (id)
);

CREATE INDEX IDX_store_user_audit_store ON store_user_audit(store_id, created_at);
CREATE INDEX IDX_store_user_audit_user ON store_user_audit(user_id, created_at);
