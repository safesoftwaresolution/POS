-- Registro de los borrados definitivos de usuarios (antes no quedaba rastro de quien borro a quien ni cuando).
-- Cada fila es inmutable: la aplicacion solo inserta. Guarda una copia de los datos del usuario, asi que
-- no tiene llave foranea: debe sobrevivir al borrado. Sin datos sensibles (ni contrasena ni tokens).
-- Los borrados de locales ya quedan en store_status_audit (new_status = 'DELETED').
CREATE TABLE user_deletion_audit (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY,
    user_id      BIGINT       NOT NULL,
    username     VARCHAR(50)  NOT NULL,
    full_name    VARCHAR(100),
    email        VARCHAR(100),
    role         VARCHAR(30),
    store_id     BIGINT,
    kind         VARCHAR(20)  NOT NULL,
    performed_by VARCHAR(100),
    created_at   TIMESTAMP    NOT NULL,

    CONSTRAINT PK_user_deletion_audit PRIMARY KEY (id)
);

CREATE INDEX IDX_user_deletion_audit_created ON user_deletion_audit(created_at);
CREATE INDEX IDX_user_deletion_audit_store ON user_deletion_audit(store_id, created_at);
