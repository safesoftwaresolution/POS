-- V33__Alegra_Local_Numbering.sql
-- Alegra no asigna el consecutivo: el sistema envia el numero y la resolucion completa en cada documento.
-- Esta migracion crea los rangos locales y el libro de numeros asignados, y agrega el company.id de Alegra
-- por local/entorno y el identificador del documento en el proveedor.
-- Seguro en H2: sin CHECK ... IN (...); los valores de 'environment' y 'document' se validan en la aplicacion.

-- Rangos de numeracion por local, entorno y tipo de documento (01 factura, 91 nota credito, 92 nota debito).
CREATE TABLE billing_numbering_range (
    id                BIGINT       GENERATED BY DEFAULT AS IDENTITY,
    store_id          BIGINT       NOT NULL,
    environment       VARCHAR(12)  NOT NULL,
    document          VARCHAR(2)   NOT NULL,
    prefix            VARCHAR(4)   NOT NULL,
    resolution_number VARCHAR(14),
    min_number        BIGINT       NOT NULL,
    max_number        BIGINT       NOT NULL,
    next_number       BIGINT       NOT NULL,
    start_date        DATE,
    end_date          DATE,
    technical_key     VARCHAR(255),
    active            BOOLEAN      NOT NULL DEFAULT TRUE,
    deleted           BOOLEAN      NOT NULL DEFAULT FALSE,
    created_at        TIMESTAMP    NOT NULL,
    updated_at        TIMESTAMP    NOT NULL,

    CONSTRAINT PK_billing_numbering_range PRIMARY KEY (id),
    CONSTRAINT FK_billing_numbering_range_store FOREIGN KEY (store_id) REFERENCES stores(id),
    CONSTRAINT UK_billing_numbering_range UNIQUE (store_id, environment, document, prefix, resolution_number)
);

CREATE INDEX IDX_billing_numbering_range_active
    ON billing_numbering_range(store_id, environment, document, active);

-- Libro de asignaciones: una referencia (venta, nota) recibe un solo numero aunque se reintente.
CREATE TABLE billing_document_number (
    id              BIGINT       GENERATED BY DEFAULT AS IDENTITY,
    store_id        BIGINT       NOT NULL,
    environment     VARCHAR(12)  NOT NULL,
    document        VARCHAR(2)   NOT NULL,
    reference_code  VARCHAR(100) NOT NULL,
    range_id        BIGINT       NOT NULL,
    prefix          VARCHAR(4)   NOT NULL,
    number          BIGINT       NOT NULL,
    idempotency_key VARCHAR(36),
    completed       BOOLEAN      NOT NULL DEFAULT FALSE,
    created_at      TIMESTAMP    NOT NULL,
    updated_at      TIMESTAMP    NOT NULL,

    CONSTRAINT PK_billing_document_number PRIMARY KEY (id),
    CONSTRAINT FK_billing_document_number_store FOREIGN KEY (store_id) REFERENCES stores(id),
    CONSTRAINT FK_billing_document_number_range FOREIGN KEY (range_id) REFERENCES billing_numbering_range(id),
    CONSTRAINT UK_billing_document_number_reference UNIQUE (store_id, environment, document, reference_code),
    CONSTRAINT UK_billing_document_number_range_number UNIQUE (range_id, number)
);

-- company.id de Alegra por local y entorno (no es un secreto, pero se trata como configuracion del back office).
ALTER TABLE store_billing_config ADD COLUMN sandbox_company_id VARCHAR(64);
ALTER TABLE store_billing_config ADD COLUMN production_company_id VARCHAR(64);

-- Identificador del documento en el proveedor (para consultarlo y conciliar reintentos).
ALTER TABLE electronic_invoices ADD COLUMN provider_document_id VARCHAR(64);
ALTER TABLE electronic_credit_notes ADD COLUMN provider_document_id VARCHAR(64);
ALTER TABLE electronic_debit_notes ADD COLUMN provider_document_id VARCHAR(64);
