-- A registration is reserved before provider HTTP and its receipt is saved before attaching
-- the company to store configuration. An uncertain CREATE is never retried blindly.
CREATE TABLE billing_company_registration (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY,
    store_id              BIGINT NOT NULL,
    environment           VARCHAR(12) NOT NULL,
    provider_name         VARCHAR(32) NOT NULL,
    identification        VARCHAR(30) NOT NULL,
    operation_id          VARCHAR(36) NOT NULL,
    state                 VARCHAR(24) NOT NULL,
    provider_company_id   VARCHAR(64),
    processing_started_at TIMESTAMP NOT NULL,
    updated_at            TIMESTAMP NOT NULL,

    CONSTRAINT PK_billing_company_registration PRIMARY KEY (id),
    CONSTRAINT FK_billing_company_registration_store FOREIGN KEY (store_id) REFERENCES stores(id),
    CONSTRAINT UK_billing_company_registration_store UNIQUE (store_id, environment, provider_name),
    CONSTRAINT UK_billing_company_registration_company UNIQUE (provider_name, environment, provider_company_id)
);
