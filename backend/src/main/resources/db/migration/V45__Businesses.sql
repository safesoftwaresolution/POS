-- Negocios con varias sucursales (fase 1, ver backend/docs/modules/businesses/spec.md).
-- Una sucursal sigue siendo un local (stores): solo se agrega la agrupacion. Un local sin negocio
-- (business_id NULL) se comporta exactamente como antes.
-- billing_mode y catalog_mode son VARCHAR sin CHECK ... IN (bug de H2 al validarlos desde otra conexion);
-- el enum de Java los valida.
CREATE TABLE businesses (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY,
    name          VARCHAR(100) NOT NULL,
    owner_user_id BIGINT       NOT NULL,
    main_store_id BIGINT       NOT NULL,
    billing_mode  VARCHAR(20)  NOT NULL,
    catalog_mode  VARCHAR(20)  NOT NULL,
    max_branches  INT          NOT NULL,
    created_at    TIMESTAMP    NOT NULL,
    updated_at    TIMESTAMP    NOT NULL,

    CONSTRAINT PK_businesses PRIMARY KEY (id),
    CONSTRAINT UK_businesses_owner UNIQUE (owner_user_id),
    CONSTRAINT UK_businesses_main_store UNIQUE (main_store_id),
    CONSTRAINT FK_businesses_owner FOREIGN KEY (owner_user_id) REFERENCES users(id),
    CONSTRAINT FK_businesses_main_store FOREIGN KEY (main_store_id) REFERENCES stores(id)
);

ALTER TABLE stores ADD COLUMN business_id BIGINT;
ALTER TABLE stores ADD CONSTRAINT FK_stores_business FOREIGN KEY (business_id) REFERENCES businesses(id);
CREATE INDEX IDX_stores_business ON stores(business_id);

-- Historial inmutable de cambios hechos desde el backoffice. Sin FKs: guarda una copia de los datos,
-- igual que store_status_audit y store_user_audit, para sobrevivir a borrados.
CREATE TABLE business_audit (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY,
    business_id       BIGINT       NOT NULL,
    business_name     VARCHAR(100),
    action            VARCHAR(20)  NOT NULL,
    affected_store_id BIGINT,
    detail            VARCHAR(255),
    performed_by      VARCHAR(100),
    created_at        TIMESTAMP    NOT NULL,

    CONSTRAINT PK_business_audit PRIMARY KEY (id)
);

CREATE INDEX IDX_business_audit_business ON business_audit(business_id, created_at);
